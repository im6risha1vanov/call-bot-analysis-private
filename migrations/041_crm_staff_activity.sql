ALTER TABLE employees ADD COLUMN IF NOT EXISTS archived_at timestamptz;

CREATE TABLE IF NOT EXISTS crm_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    actor_name text NOT NULL,
    actor_role text NOT NULL CHECK (actor_role IN ('manager', 'director')),
    action text NOT NULL,
    status integer NOT NULL
);

CREATE INDEX IF NOT EXISTS crm_activity_company_id_idx ON crm_activity (client_id, id DESC);

CREATE TABLE IF NOT EXISTS crm_economics_viewers (
    client_id integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    telegram_user_id bigint NOT NULL,
    PRIMARY KEY (client_id, telegram_user_id)
);
