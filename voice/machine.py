"""
Автоответчик, голосовая почта оператора или ИИ-секретарь абонента: узнаём по словам, без модели.

По записям звонков робота 26.10 (24 звонка без дозвона съели три четверти всех токенов):
- голосовая почта оператора говорит первой, ещё до «алло»: «Вызываемый абонент не отвечает (недоступен).
  Звонок был перенаправлен на голосовой почтовый ящик. Вы можете оставить сообщение после звукового сигнала»;
- ИИ-секретари (у операторов и банков) отвечают «Скажите, что нужно передать», «Произошёл сбой на моей стороне»,
  «Сообщение записано и будет передано абоненту», «Меня зовут Ассистент». Робот разговаривал с ними до минуты
  и тратил до 30 тысяч токенов.
"""

from __future__ import annotations

import re

PATTERNS = [
    r"абонент\w*\s+(не\s+отвеча|недоступ|не\s+доступ|временно|выключ|находится\s+вне)",
    r"вне\s+зоны\s+действия",
    r"почтов\w*\s+ящик",
    r"после\s+(звукового\s+)?сигнала",
    r"(оставьте|оставить)\s+(\w+\s+)?сообщени",
    r"переда\w*\s+абонент",
    r"записать\s+(ваше\s+)?сообщени",
    r"не\s+смогу\s+записать",
    # секретари пересказывают, что «записали», и сбоят на распознавании (записи 26.10)
    r"(вот\s+)?что\s+(я\s+)?записал",
    r"итогов\w*\s+запис",
    r"(я\s+)?записала,?\s+что\s+вы",
    r"не\s+удалось\s+обработать",
    r"готов\w*\s+записать",
    r"сообщение\s+(записано|будет\s+передано|передам)",
    r"что\s+(именно\s+)?(нужно|надо|хотите|хотели\s+бы|вы\s+хотите)\s+(\w+\s+)?передать",
    r"сбой\s+на\s+моей\s+сторон",
    r"(помощник|ассистент|секретар\w*)\s+абонент",
    r"меня\s+зовут\s+ассистент",
    r"я\s+(виртуальный|цифровой)\s+(помощник|ассистент|секретарь)",
    r"номер\s+(не\s+существует|набран\s+неверно)",
]
_RE = re.compile("|".join(f"(?:{p})" for p in PATTERNS))


def detect(text: str) -> str:
    """Кусок фразы, по которому узнали автоответчик, или "" — похоже на живого человека."""
    m = _RE.search((text or "").lower().replace("ё", "е"))
    return m.group(0) if m else ""
